def make_brief(title):
    title=re.sub(r'\[[^\]]*\]|\([^)]*\)',' ',title)
    title=title.replace('한국은행','한은').strip()
    chosen=next((p for p in PATTERNS if re.search(p[1],title)),None)
    if not chosen:return None
    # Quoted remarks/headline adverbs are not reliable subjects: abstain.
    m=re.match(r'([가-힣A-Za-z][가-힣A-Za-z0-9&·]{1,22})',title)
    if not m:return None
    subject=m.group(1)
    subject=re.sub(r'(에서는|에서|으로|은|는)$','',subject) if len(subject)>3 else subject
    if subject in {'오늘','내일','올해','내년','단독','속보','최근','정부','금융','경제','주가','이유','결국','왜','이렇게','이제','사설'}:return None
    kind,_,suffixes,titles,outline=chosen
    if kind=='과세':
        for concept in ('배당소득','양도소득','금융투자소득','상속','증여'):
            if concept in title:subject=concept;break
    if kind=='과세' and re.search('가상자산|암호화폐|코인',title):subject='가상자산'
    if kind=='금리' and '기준금리' in title and re.search('한은|한국은행|금통위',title):subject='한국은행'
    # Avoid duplicated concept words, e.g. '가상자산 과세 과세'.
    prefix=lambda s:subject+' '+(s[len(kind):].strip() if subject.endswith(kind) and s.startswith(kind) else s)
    queries=[prefix(s).strip() for s in suffixes]
    return {'subject':subject,'kind':kind,'keyword':queries[0],'queries':queries,
            'titles':[prefix(t).strip() for t in titles], 'topic':queries[0]+' 관련 변화와 독자가 확인할 조건',
            'outline':outline,'intent_basis':'규칙 기반 예상 검색의도; 실제 검색어 로그 아님'}

